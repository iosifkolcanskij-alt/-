function reduceToDigit(n, allowMaster) {
  if (allowMaster && (n === 11 || n === 22 || n === 33)) return n;
  while (n > 9 && (!allowMaster || (n !== 11 && n !== 22 && n !== 33))) {
    n = String(n).split('').reduce((a, b) => a + +b, 0);
  }
  return n;
}

function calcLifePathNumber(day, month, year) {
  const d = reduceToDigit(day, true);
  const m = reduceToDigit(month, true);
  const y = String(year).split('').reduce((a, b) => a + +b, 0);
  const yR = reduceToDigit(y, true);
  return reduceToDigit(d + m + yR, true);
}

