function generatePortraitText(data) {
  const parts = [];
  if (data.mbti) {
    const m = MBTI_DESC[data.mbti];
    if (m) parts.push(`По типу личности MBTI вы — <strong>${m.name} «${m.nick}»</strong>: ${m.desc.split('.')[0]}. В когнитивном плане это значит, что вы обычно опираетесь на привычный для себя способ воспринимать информацию, принимать решения и выстраивать жизненный ритм.`);
  }
  if (data.temperament) {
    const t = TEMP_DESC[data.temperament];
    if (t) parts.push(`Ваш темперамент — <strong>${t.emoji} ${t.name}</strong>: ${t.description.split('.')[0]}. Темперамент добавляет к типологии телесный и эмоциональный слой: он показывает, насколько быстро вы разгоняетесь, как проживаете напряжение и в каком режиме дольше сохраняете устойчивость.`);
  }
  if (data.zodiac) {
    const z = data.zodiac;
    parts.push(`Ваш знак Зодиака — <strong>${z.emoji} ${z.name}</strong> (${z.element} ${z.elementEmoji}): ${z.desc.split('.')[0]}. Этот слой не заменяет психологию, но помогает увидеть ваш образ через архетипы, ценности и символический язык стихий.`);
  }
  if (data.chineseZodiac) {
    const cz = data.chineseZodiac;
    parts.push(`По китайскому гороскопу вы — <strong>${cz.emoji} ${cz.name}</strong> (элемент ${cz.element}): ${cz.desc.split('.')[0]}. В сочетании с западным знаком это создаёт дополнительный культурный ракурс, через который можно осмыслить сильные стороны, социальный стиль и мотивы поведения.`);
  }
  if (parts.length >= 2) {
    parts.push('Если смотреть на результаты целиком, ваш портрет складывается из нескольких уровней: тип мышления, темп реакций, способы строить отношения и символический фон даты рождения. Именно пересечение этих слоёв обычно даёт самый полезный материал для самонаблюдения и личностного роста.');
  }
  return parts.length > 0 ? parts : ["Пройдите тесты и введите дату рождения, чтобы увидеть ваш портрет личности."];
}
