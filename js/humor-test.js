function initHumorTest() {
  humorGender = null;
  humorBlockAnswers = [];
  humorCurrentBlock = 0;
  humorBlockResults = [];
  renderHumorGenderSelect();
}

function renderHumorGenderSelect() {
  var cont = document.getElementById('humorTest');
  if (!cont) return;
  cont.innerHTML = [
    '<div class="humor-gender-select">',
    '  <p class="humor-gender-title">Прежде чем начать, выберите ваш пол:</p>',
    '  <div class="humor-gender-btns">',
    '    <button class="btn humor-gender-btn humor-gender-woman" onclick="humorSelectGender(\'woman\')">',
    '      <span class="humor-gender-icon">♀</span>',
    '      <span>Женщина</span>',
    '    </button>',
    '    <button class="btn humor-gender-btn humor-gender-man" onclick="humorSelectGender(\'man\')">',
    '      <span class="humor-gender-icon">♂</span>',
    '      <span>Мужчина</span>',
    '    </button>',
    '  </div>',
    '</div>'
  ].join('');
}

function humorSelectGender(gender) {
  humorGender = gender;
  humorBlockAnswers = [[], [], [], [], [], []];
  humorCurrentBlock = 0;
  humorBlockResults = [];
  renderHumorBlock();
}

function renderHumorBlock() {
  var cont = document.getElementById('humorTest');
  if (!cont) return;

  var questions = humorGender === 'woman' ? HUMOR_QUESTIONS_WOMEN : HUMOR_QUESTIONS_MEN;
  var block = questions[humorCurrentBlock];
  var answers = humorBlockAnswers[humorCurrentBlock] || [];

  var html = [
    '<div class="humor-block">',
    '  <div class="humor-progress">',
    '    <div class="humor-progress-bar" style="width:' + Math.round((humorCurrentBlock / 6) * 100) + '%"></div>',
    '  </div>',
    '  <div class="humor-block-label">Блок ' + (humorCurrentBlock + 1) + ' из 6</div>',
    '  <h4 class="humor-block-title">' + block.title + '</h4>',
    '  <div class="humor-questions">'
  ];

  block.questions.forEach(function(q, i) {
    var ans = answers[i];
    html.push(
      '<div class="humor-question' + (ans !== undefined ? ' humor-answered' : '') + '">',
      '  <p class="humor-q-text">' + (i + 1) + '. ' + q + '</p>',
      '  <div class="humor-q-btns">',
      '    <button class="humor-ans-btn' + (ans === 1 ? ' humor-ans-yes' : '') + '" onclick="humorAnswer(' + i + ', 1)">Да</button>',
      '    <button class="humor-ans-btn' + (ans === 0 ? ' humor-ans-no' : '') + '" onclick="humorAnswer(' + i + ', 0)">Нет</button>',
      '  </div>',
      '</div>'
    );
  });

  html.push('</div>');

  var allAnswered = answers.length === 5 && answers.every(function(a) { return a !== undefined; });
  html.push(
    '<button class="btn btn-primary humor-next-btn" onclick="humorNextBlock()" ' + (allAnswered ? '' : 'disabled') + '>',
    humorCurrentBlock < 5 ? 'Следующий блок →' : 'Узнать результат',
    '</button>',
    '</div>'
  );

  cont.innerHTML = html.join('');
}

function humorAnswer(questionIdx, val) {
  if (!humorBlockAnswers[humorCurrentBlock]) {
    humorBlockAnswers[humorCurrentBlock] = [];
  }
  humorBlockAnswers[humorCurrentBlock][questionIdx] = val;
  renderHumorBlock();
}

function humorNextBlock() {
  var answers = humorBlockAnswers[humorCurrentBlock];
  if (!answers || answers.length < 5 || answers.some(function(a) { return a === undefined; })) return;

  var ones = answers.filter(function(a) { return a === 1; }).length;
  humorBlockResults.push(ones >= 3 ? 1 : 0);

  if (humorCurrentBlock < 5) {
    humorCurrentBlock++;
    renderHumorBlock();
    var cont = document.getElementById('humorTest');
    if (cont) cont.scrollIntoView({ behavior: 'smooth', block: 'start' });
  } else {
    showHumorResult();
  }
}

function showHumorResult() {
  var code = humorBlockResults.join('');
  var resultsMap = humorGender === 'woman' ? HUMOR_RESULTS_WOMEN : HUMOR_RESULTS_MEN;
  var description = resultsMap[code] || 'уникальная личность вне всяких категорий';
  var genderLabel = humorGender === 'woman' ? 'Женский тест' : 'Мужской тест';

  var cont = document.getElementById('humorTest');
  if (!cont) return;

  cont.innerHTML = [
    '<div class="humor-result">',
    '  <div class="humor-result-code">',
    '    <span class="humor-code-label">Ваш код:</span>',
    '    <span class="humor-code-digits">' + code.split('').map(function(d, i) {
      return '<span class="humor-digit humor-digit-' + d + '" title="Блок ' + (i+1) + '">' + d + '</span>';
    }).join('') + '</span>',
    '  </div>',
    '  <div class="humor-result-badge">',
    '    <span class="humor-result-icon">😄</span>',
    '    <div class="humor-result-text">',
    '      <div class="humor-result-label">Вы —</div>',
    '      <div class="humor-result-desc">' + description + '</div>',
    '    </div>',
    '  </div>',
    '  <div class="humor-result-breakdown">',
    '    <div class="humor-breakdown-title">Ответы по блокам</div>',
    '    <div class="humor-breakdown-grid">',
    humorBlockResults.map(function(r, i) {
      return '<div class="humor-breakdown-item humor-breakdown-' + r + '"><span class="hbi-num">' + (i+1) + '</span><span class="hbi-val">' + (r === 1 ? 'Да' : 'Нет') + '</span></div>';
    }).join(''),
    '    </div>',
    '  </div>',
    '  <div class="humor-result-actions">',
    '    <button class="btn btn-primary" onclick="initHumorTest()">Пройти снова</button>',
    '    <button class="btn btn-outline" onclick="backToTestsHub()">К списку тестов</button>',
    '  </div>',
    '</div>'
  ].join('');
}
